#!/usr/bin/env bash
# Compiles the post-processing shaders in SpaceCadetPinball/shaders/ into PostEffectShaders.h:
# SPIR-V (Vulkan) and DXIL (Direct3D 12) from the HLSL with a pinned DXC, MSL (Metal) from the hand-written .msl files.
# The header is committed, so building the game needs none of this. Run it after changing a shader.
set -euo pipefail

cd "$(dirname "$0")/../SpaceCadetPinball/shaders"
dxc_version=v1.9.2609
dxc_archive=linux_dxc_2026_09_28.x86_x64.tar.gz
dxc_sha256=96faadc7f5c282d2ffda49804beb4c3ee38127bc252b723234e3c5cdf7aa39a1
dxc_dir=${XDG_CACHE_HOME:-$HOME/.cache}/SpaceCadetPinball/dxc-$dxc_version

if [ ! -x "$dxc_dir/bin/dxc" ]; then
	mkdir -p "$dxc_dir"
	curl -sSfL -o "$dxc_dir/$dxc_archive" \
		"https://github.com/microsoft/DirectXShaderCompiler/releases/download/$dxc_version/$dxc_archive"
	echo "$dxc_sha256  $dxc_dir/$dxc_archive" | sha256sum -c --quiet
	tar xzf "$dxc_dir/$dxc_archive" -C "$dxc_dir"
fi
dxc() { LD_LIBRARY_PATH="$dxc_dir/lib" "$dxc_dir/bin/dxc" -Wno-ignored-attributes "$@"; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# One byte array per shader and format
emit() { # name, file
	python3 - "$1" "$2" <<'PY'
import sys
name, path = sys.argv[1], sys.argv[2]
data = open(path, 'rb').read()
print(f"static const unsigned char {name}[] = {{")
for i in range(0, len(data), 16):
    print("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
print("};")
PY
}

{
	echo "// Generated by tools/build-shaders.sh from the shaders in this folder; don't edit."
	echo "#pragma once"
	echo
	for shader in *.frag.hlsl; do
		name=${shader%.frag.hlsl}
		dxc -T ps_6_0 -E main -spirv -fspv-target-env=vulkan1.0 "$shader" -Fo "$tmp/$name.spv"
		dxc -T ps_6_0 -E main "$shader" -Fo "$tmp/$name.dxil"
		emit "${name}_frag_spv" "$tmp/$name.spv"
		emit "${name}_frag_dxil" "$tmp/$name.dxil"
		# Metal compiles the source text when the shader is created
		emit "${name}_frag_msl" "$name.frag.msl"
		echo
	done
} > PostEffectShaders.h

echo "Wrote SpaceCadetPinball/shaders/PostEffectShaders.h"
